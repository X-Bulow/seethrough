#!/usr/bin/env bash
# Install the clang and Valgrind versions used by the Ubuntu lab setup.
set -euo pipefail

packages=(
  'clang=1:21.1.6-71'
  'clang-21=1:21.1.8-6ubuntu1'
  'valgrind=1:3.26.0-0ubuntu1'
)
pending=()
for spec in "${packages[@]}"; do
  name="${spec%%=*}"
  expected="${spec#*=}"
  actual="$(dpkg-query -W -f='${Status} ${Version}' "$name" 2>/dev/null || true)"
  if [[ "$actual" == "install ok installed $expected" ]]; then
    echo "$name: $expected already installed"
  else
    pending+=("$spec")
  fi
done

if [[ ${#pending[@]} -gt 0 ]]; then
  if [[ "$EUID" -eq 0 ]]; then apt=(apt-get); else apt=(sudo apt-get); fi
  "${apt[@]}" update
  "${apt[@]}" install -y "${pending[@]}"
fi

# Verify the installed packages and the commands used by the existing flags.mk.
for spec in "${packages[@]}"; do
  name="${spec%%=*}"
  expected="${spec#*=}"
  actual="$(dpkg-query -W -f='${Status} ${Version}' "$name")"
  if [[ "$actual" != "install ok installed $expected" ]]; then
    echo "$name: expected $expected; found $actual" >&2
    exit 1
  fi
done
clang_version="$(clang --version)"
valgrind_version="$(valgrind --version)"
if [[ "$clang_version" != *'clang version 21.1.8 '* || "$valgrind_version" != 'valgrind-3.26.0' ]]; then
  echo "clang or valgrind on PATH does not match the pinned versions:" >&2
  printf '%s\n' "$clang_version" "$valgrind_version" >&2
  exit 1
fi

echo "== SQLite amalgamations (B3, A7): pinned, into vendor/ or \$SEETHROUGH_CACHE"
"$(dirname "$0")/fetch-sqlite.sh" 3.53.3
"$(dirname "$0")/fetch-sqlite.sh" 3.22.0
echo "SQLite speedtest1 uses a separate 3.50.4 source; fetch it with benchmarks/sqlite-speedtest1/fetch.sh"

versions_file="$(dirname "$0")/VERSIONS.txt"
{
  echo "# generated by tools/setup-server.sh on $(date -Is)"
  for spec in "${packages[@]}"; do
    name="${spec%%=*}"
    printf '%s=' "$name"
    dpkg-query -W -f='${Version}\n' "$name"
  done
  echo "clang: ${clang_version%%$'\n'*}"
  echo "valgrind: $valgrind_version"
} > "$versions_file"
echo "Versions recorded in $versions_file"
